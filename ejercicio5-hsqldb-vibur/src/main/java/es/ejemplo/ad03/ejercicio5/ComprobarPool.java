package es.ejemplo.ad03.ejercicio5;

import org.vibur.dbcp.ViburDBCPDataSource;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

public final class ComprobarPool {
    private ComprobarPool() {
    }

    public static void main(String[] args) throws SQLException {
        try {
            Files.createDirectories(Path.of("data"));
        } catch (IOException exception) {
            throw new SQLException("No se pudo crear el directorio de la base HSQLDB.", exception);
        }

        ViburDBCPDataSource dataSource = new ViburDBCPDataSource();
        dataSource.setJdbcUrl("jdbc:hsqldb:file:./data/ad03;shutdown=true");
        dataSource.setUsername("SA");
        dataSource.setPassword("");
        dataSource.setPoolInitialSize(1);
        dataSource.setPoolMaxSize(5);
        dataSource.setConnectionTimeoutInMs(5_000);
        dataSource.setConnectionIdleLimitInMs(30_000);

        try {
            dataSource.start();
            try (Connection connection = dataSource.getConnection()) {
                if (!connection.isValid(2)) {
                    throw new SQLException("La conexión de HSQLDB no es válida.");
                }
                System.out.println("Conexión HSQLDB válida.");

                try (Statement statement = connection.createStatement()) {
                    statement.executeUpdate("""
                            CREATE TABLE IF NOT EXISTS comprobacion (
                                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                mensaje VARCHAR(200) NOT NULL
                            )
                            """);
                    statement.executeUpdate(
                            "INSERT INTO comprobacion (mensaje) VALUES ('Pool Vibur operativo')");
                    try (ResultSet result = statement.executeQuery(
                            "SELECT id, mensaje FROM comprobacion ORDER BY id")) {
                        while (result.next()) {
                            System.out.printf("%d: %s%n",
                                    result.getInt("id"),
                                    result.getString("mensaje"));
                        }
                    }
                }
            }
        } finally {
            dataSource.close();
        }
    }
}
